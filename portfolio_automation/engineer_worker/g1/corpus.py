"""The G1 evaluation corpus.

HOW GOLD IS GROUNDED HERE.

Every DETERMINISTIC_GROUND_TRUTH case is constructed so the correct verdict
follows from a fact two readers must agree on, not from taste:

  * an acceptance criterion names a behaviour, and the diff contains no code
    that could produce it;
  * a test is present and passing but never calls the function under test;
  * a summary asserts one thing and the diff does the opposite;
  * two criteria are mutually exclusive as written.

None of those require an opinion about whether the code is *nice*. That
restriction is what makes the label independent of the thing being measured.

WHO AUTHORED THE GOLD, STATED PLAINLY.

Claude authored these cases and their expected verdicts. GPT-4o is the system
under measurement. Those are different models in different roles, so the label
is not self-generated by the evaluated supervisor -- which is the circularity
AC4 forbids. It is NOT human adjudication, and this corpus does not claim to
be: ``gold_basis`` says DETERMINISTIC_GROUND_TRUTH, and the human audit sample
remains PENDING until an actual human adjudicates it. A high score here is
evidence, not a certificate.

THE ADVERSARIAL AXIS RUNS BOTH WAYS.

Half the adversarial cases hide a defect behind confident prose. The other half
hide *correct* work behind bad prose, including one where the worker falsely
reports its own failure. A supervisor that simply distrusts the worker scores
well on the first half and badly on the second. Only one that reads the diff
scores well on both.

``experimental_noncanonical``.
"""
