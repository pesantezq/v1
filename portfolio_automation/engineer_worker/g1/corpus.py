ALL_CASES: tuple[EvaluationCaseV0, ...] = tuple(
    _PASS_CASES + _REPAIR_CASES + _ESCALATE_CASES + _ABSTAIN_CASES)


class SplitLeakError(AssertionError):
    """HELD_OUT was reached through a development-facing accessor."""


def cases(split: Split | None = None) -> tuple[EvaluationCaseV0, ...]:
    if split is None:
        return ALL_CASES
    return tuple(c for c in ALL_CASES if c.split is split)


def development_cases() -> tuple[EvaluationCaseV0, ...]:
    """The ONLY accessor that may be used while tuning a prompt or model.

    Named rather than parameterised so that reading HELD_OUT during tuning has
    to be written down explicitly, where a reviewer can see it."""
    return cases(Split.DEVELOPMENT)


def held_out_cases() -> tuple[EvaluationCaseV0, ...]:
    """Scoring only. Never for tuning."""
    return cases(Split.HELD_OUT)


def rotating_cases() -> tuple[EvaluationCaseV0, ...]:
    return cases(Split.ROTATING_FRESH)


def by_id() -> dict[str, EvaluationCaseV0]:
    return {c.case_id: c for c in ALL_CASES}


def assert_corpus_coherent() -> None:
    """Structural facts a corpus must satisfy before it can measure anything."""
    ids = [c.case_id for c in ALL_CASES]
    dupes = sorted({i for i in ids if ids.count(i) > 1})
    if dupes:
        raise G1ContractError(f"duplicate case ids: {dupes}")
    for split in Split:
        if not cases(split):
            raise G1ContractError(
                f"split {split.value} is empty; AC5 requires all three to be "
                "represented, and an empty split silently removes a guarantee")
    expected = {c.expected_supervisor_verdict for c in ALL_CASES}
    missing = {V.PASS, V.REPAIR, V.ESCALATE, V.ABSTAIN} - expected
    if missing:
        raise G1ContractError(
            f"no cases expect {sorted(v.value for v in missing)}; a corpus that "
            "never expects a verdict cannot measure it")
    for c in ALL_CASES:
        if V.PASS in c.acceptable_alternate_verdicts and \
                c.expected_supervisor_verdict is not V.PASS:
            raise G1ContractError(f"{c.case_id}: PASS admitted as alternate")


def corpus_manifest() -> dict[str, Any]:
    return {
        "schema_version": CORPUS_SCHEMA_VERSION, "schema_kind": G1_SCHEMA_KIND,
        "rotation_epoch": ROTATION_EPOCH,
        "n_cases": len(ALL_CASES),
        "by_split": {s.value: len(cases(s)) for s in Split},
        "by_expected": {v.value: sum(
            1 for c in ALL_CASES if c.expected_supervisor_verdict is v)
            for v in (V.PASS, V.REPAIR, V.ESCALATE, V.ABSTAIN)},
        "by_severity": {s.value: sum(1 for c in ALL_CASES if c.severity is s)
                        for s in Severity},
        "by_gold_basis": {b.value: sum(1 for c in ALL_CASES if c.gold_basis is b)
                          for b in GoldBasis},
        "by_source_class": {s.value: sum(1 for c in ALL_CASES
                                         if c.source_class is s)
                            for s in SourceClass},
        "fingerprints": {c.case_id: c.fingerprint() for c in ALL_CASES},
    }
